# export-wiki-raw.ps1
# Builds the immutable "raw" layer of the LLM wiki: one Markdown digest per dossier
# in wiki/raw/dossiers/<id>.md, merged from data/curated.js, data/oeil-data.json,
# data/secondary-data.json and data/changes.json.
# The wiki agent reads these digests; it never edits them (re-run this script instead).
# Keep this file ASCII-only (Windows PowerShell 5.1 misreads non-ASCII source).

param(
  [string]$Root = (Split-Path -Parent $PSScriptRoot)
)

$ErrorActionPreference = 'Stop'
$utf8 = New-Object System.Text.UTF8Encoding($false)

function Read-Json($path) {
  if (-not (Test-Path $path)) { return $null }
  return [IO.File]::ReadAllText($path, $utf8) | ConvertFrom-Json
}

function Fmt-Link($text, $href) {
  if ($href) { return "[$text]($href)" } else { return $text }
}

$curatedText = [IO.File]::ReadAllText((Join-Path $Root 'data/curated.js'), $utf8)
$oeil        = Read-Json (Join-Path $Root 'data/oeil-data.json')
$secondary   = Read-Json (Join-Path $Root 'data/secondary-data.json')
$changes     = Read-Json (Join-Path $Root 'data/changes.json')

$outDir = Join-Path $Root 'wiki/raw/dossiers'
New-Item -ItemType Directory -Force $outDir | Out-Null

# Split curated.js into top-level entry blocks: each starts with "  {" followed by an id line.
$starts = [regex]::Matches($curatedText, '(?m)^  \{\s*\r?\n\s+id: "([^"]+)"')
$endMarker = $curatedText.LastIndexOf('];')
$count = 0

for ($i = 0; $i -lt $starts.Count; $i++) {
  $m = $starts[$i]
  $id = $m.Groups[1].Value
  $end = if ($i + 1 -lt $starts.Count) { $starts[$i + 1].Index } else { $endMarker }
  $block = $curatedText.Substring($m.Index, $end - $m.Index).TrimEnd().TrimEnd(',')
  # Drop section-divider comments that belong to the next entry.
  $block = [regex]::Replace($block, '(?s)\s*/\*\s*=+.*?=+\s*\*/\s*$', '')

  $oeilRef = ''
  $om = [regex]::Match($block, 'oeil: "([^"]*)"')
  if ($om.Success) { $oeilRef = $om.Groups[1].Value }

  $sb = New-Object System.Text.StringBuilder
  [void]$sb.AppendLine("# RAW DIGEST: $id")
  [void]$sb.AppendLine('')
  [void]$sb.AppendLine("- dossier id: ``$id``")
  [void]$sb.AppendLine("- OEIL procedure: " + $(if ($oeilRef) { "``$oeilRef``" } else { '(none - secondary act or not yet proposed)' }))
  [void]$sb.AppendLine("- OEIL fetched: " + $(if ($oeil) { $oeil.generatedAt } else { 'n/a' }))
  [void]$sb.AppendLine("- Secondary fetched: " + $(if ($secondary) { $secondary.generatedAt } else { 'n/a' }))
  [void]$sb.AppendLine('- Generated by tools/export-wiki-raw.ps1. Do not edit by hand.')
  [void]$sb.AppendLine('')

  # ---- curated layer
  [void]$sb.AppendLine('## 1. Curated layer (data/curated.js, hand-maintained)')
  [void]$sb.AppendLine('')
  [void]$sb.AppendLine('```js')
  [void]$sb.AppendLine($block)
  [void]$sb.AppendLine('```')
  [void]$sb.AppendLine('')

  # ---- OEIL
  [void]$sb.AppendLine('## 2. OEIL (European Parliament Legislative Observatory)')
  [void]$sb.AppendLine('')
  $p = $null
  if ($oeilRef -and $oeil -and $oeil.procedures) { $p = $oeil.procedures.$oeilRef }
  if (-not $p) {
    [void]$sb.AppendLine('No OEIL record.')
  } else {
    [void]$sb.AppendLine("- Title: $($p.title)")
    [void]$sb.AppendLine("- URL: $($p.url)")
    [void]$sb.AppendLine("- Type: $($p.procedureType)")
    [void]$sb.AppendLine("- Instrument: $($p.instrument)")
    [void]$sb.AppendLine("- Status: $($p.status)")
    if ($p.mainAct) { [void]$sb.AppendLine("- Final act: " + (Fmt-Link $p.mainAct $p.mainActHref) + " ($($p.mainActOj))") }
    foreach ($r in @($p.relations)) { if ($r) { [void]$sb.AppendLine("- Relation: $($r.label) -> ``$($r.ref)``") } }
    foreach ($d in @($p.delegatedActs)) { if ($d) { [void]$sb.AppendLine("- Delegated act procedure: ``$($d.ref)`` ($($d.subject))") } }
    if ($p.commission) { [void]$sb.AppendLine("- Commission (raw): " + ($p.commission | ConvertTo-Json -Depth 5 -Compress)) }
    [void]$sb.AppendLine('')

    [void]$sb.AppendLine('### Committees')
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('| Role | Committee | Rapporteur(s) | Shadows | Appointed |')
    [void]$sb.AppendLine('|---|---|---|---|---|')
    foreach ($c in @($p.committees)) {
      if (-not $c) { continue }
      $rap = (@($c.rapporteurs) | Where-Object { $_ } | ForEach-Object { "$($_.name) ($($_.group))" }) -join '; '
      $sh  = (@($c.shadows)     | Where-Object { $_ } | ForEach-Object { "$($_.name) ($($_.group))" }) -join '; '
      [void]$sb.AppendLine("| $($c.role) | $($c.abbr) $($c.name) | $rap | $sh | $($c.appointed) |")
    }
    [void]$sb.AppendLine('')

    if (@($p.council | Where-Object { $_ }).Count -gt 0) {
      [void]$sb.AppendLine('### Council (raw)')
      [void]$sb.AppendLine('')
      foreach ($x in @($p.council)) { if ($x) { [void]$sb.AppendLine('- ' + ($x | ConvertTo-Json -Depth 5 -Compress)) } }
      [void]$sb.AppendLine('')
    }

    [void]$sb.AppendLine('### Key events')
    [void]$sb.AppendLine('')
    foreach ($e in @($p.events)) {
      if (-not $e) { continue }
      $refs = (@($e.refs) | Where-Object { $_ } | ForEach-Object { Fmt-Link $_.text $_.href }) -join ', '
      $line = "- $($e.date) - $($e.event)"
      if ($refs) { $line += " - $refs" }
      if ($e.summary) { $line += " - [summary]($($e.summary))" }
      [void]$sb.AppendLine($line)
    }
    [void]$sb.AppendLine('')

    if (@($p.forecasts | Where-Object { $_ }).Count -gt 0) {
      [void]$sb.AppendLine('### Forecasts')
      [void]$sb.AppendLine('')
      foreach ($f in @($p.forecasts)) { if ($f) { [void]$sb.AppendLine('- ' + ($f | ConvertTo-Json -Depth 5 -Compress)) } }
      [void]$sb.AppendLine('')
    }

    [void]$sb.AppendLine('### Documents')
    [void]$sb.AppendLine('')
    foreach ($d in (@($p.documents) | Where-Object { $_ } | Sort-Object date)) {
      $extra = if ($d.extra) { " $($d.extra)" } else { '' }
      [void]$sb.AppendLine("- $($d.date) [$($d.inst)] $($d.type)$extra - " + (Fmt-Link $d.ref $d.href))
    }
    if ($p.finalActs) {
      foreach ($fa in @($p.finalActs)) { if ($fa) { [void]$sb.AppendLine("- Final act ref: " + (Fmt-Link $fa.text $fa.href)) } }
    }
    [void]$sb.AppendLine('')
  }

  # ---- Secondary (EUR-Lex + Have Your Say)
  $sd = $null
  if ($secondary -and $secondary.dossiers) { $sd = $secondary.dossiers.$id }
  [void]$sb.AppendLine('## 3. EUR-Lex secondary acts (Cellar)')
  [void]$sb.AppendLine('')
  $acts = @()
  if ($sd) { $acts = @($sd.acts | Where-Object { $_ }) }
  if ($acts.Count -eq 0) { [void]$sb.AppendLine('None recorded.') }
  foreach ($a in ($acts | Sort-Object date -Descending)) {
    [void]$sb.AppendLine("- $($a.date) [$($a.kind)] " + (Fmt-Link $a.title $a.url) + " - CELEX $($a.celex)")
  }
  [void]$sb.AppendLine('')

  [void]$sb.AppendLine('## 4. Have Your Say initiatives (Commission Better Regulation portal)')
  [void]$sb.AppendLine('')
  $inits = @()
  if ($sd) { $inits = @($sd.initiatives | Where-Object { $_ }) }
  if ($inits.Count -eq 0) { [void]$sb.AppendLine('None recorded.') }
  foreach ($n in ($inits | Sort-Object modified -Descending)) {
    [void]$sb.AppendLine("### " + (Fmt-Link $n.title $n.url))
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine("- Type: $($n.actType); stage: $($n.stage); status: $($n.status); feedback: $($n.feedbackStatus); DG: $($n.dg)")
    [void]$sb.AppendLine("- Published: $($n.published); modified: $($n.modified)")
    foreach ($pub in @($n.publications)) {
      if (-not $pub) { continue }
      $fb = ''
      if ($pub.fbStart) { $fb = " feedback $($pub.fbStart)..$($pub.fbEnd) ($($pub.feedback) responses)" }
      $dt = if ($pub.date) { $pub.date } else { '(not yet)' }
      [void]$sb.AppendLine("  - $($pub.type) $dt$fb $($pub.reference)")
    }
    if ($n.summary) { [void]$sb.AppendLine("- Summary: $($n.summary)") }
    [void]$sb.AppendLine('')
  }

  # ---- Recent changes
  [void]$sb.AppendLine('## 5. Recent detected changes (data/changes.json)')
  [void]$sb.AppendLine('')
  $ch = @()
  if ($changes -and $changes.changes) { $ch = @($changes.changes | Where-Object { $_.dossier -eq $id }) }
  if ($ch.Count -eq 0) { [void]$sb.AppendLine('None.') }
  foreach ($x in ($ch | Sort-Object date -Descending)) {
    [void]$sb.AppendLine("- detected $($x.detected) | $($x.date) | $($x.source)/$($x.kind) | " + (Fmt-Link $x.text $x.url))
  }

  [IO.File]::WriteAllText((Join-Path $outDir "$id.md"), $sb.ToString(), $utf8)
  $count++
}

Write-Host "Wrote $count raw digests to $outDir"
